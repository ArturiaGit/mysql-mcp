"""Generate bounded design-contract artifacts. No application/runtime Schema is claimed.
Markdown request tables are authoritative for names, TS types and required flags.
Conditional validation remains in the linked API section; do not use these types as validators.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/contracts'

def section(text, heading):
    start = text.index(heading)
    level = len(re.match(r'#+', heading)[0])
    match = re.search(r'\n#{1,' + str(level) + r'} ', text[start + len(heading):])
    return text[start:start + len(heading) + match.start()] if match else text[start:]

def read(p):
    return (ROOT / p).read_text(encoding='utf-8-sig')

def fields(block, label):
    tail = block[block.index(label):]
    lines = tail.splitlines()[1:]
    result = []
    for line in lines:
        if not line.strip().startswith('|'):
            if result:
                break
            continue
        cells = re.split(r'(?<!\\)\|', line.strip())[1:-1]
        if len(cells) < 3 or not re.fullmatch(r'`[^`]+`', cells[0].strip()):
            continue
        name, kind, required = [c.strip().replace('`', '').replace('**', '').replace('\\|', '|') for c in cells[:3]]
        if kind not in ('string', 'number', 'boolean', 'TlsConfig | null'):
            raise ValueError(f'Unsupported type: {kind} ({name})')
        result.append({'name': name, 'type': kind, 'required': required == '是', 'constraints': ' | '.join(c.strip() for c in cells[3:])})
    if not result:
        raise ValueError('No fields parsed: ' + label)
    return result

def generate():
    api = read('docs/API_CONTRACT_SPEC.md')
    fe = read('docs/FRONTEND_ARCHITECTURE_SPEC.md')
    be = read('docs/BACKEND_ARCHITECTURE_SPEC.md')
    db = read('docs/DATABASE_DESIGN_SPEC.md')
    specs = [
        ('CreateProfilePayload', '6.5.3', '请求体 JSON Schema'),
        ('UpdateProfilePayload', '6.5.4', '请求体全量可写字段清单'),
        ('GlobalRateLimitPayload', '6.7.2', '请求体 JSON Schema'),
        ('UserRateLimitPayload', '6.7.4', '请求体 JSON Schema'),
        ('ExportAuditPayload', '6.8.3', '请求体 JSON Schema'),
        ('TestSshPayload', '6.5.7', '请求体 JSON Schema'),
        ('ResetPasswordPayload', '6.3.5', '请求体 JSON Schema'),
        ('DownloadQuery', '6.8.4', '查询参数'),
    ]
    # Locate SSH by route rather than assuming its subsection number.
    ssh = re.search(r'#### (\S+) [^\n]+\n- \*\*接口路径\*\*：`POST /api/v1/profiles/test-ssh`', api)[1]
    specs = [(n, ssh if n == 'TestSshPayload' else h, l) for n, h, l in specs]
    types = ['// GENERATED by scripts/generate_readiness_contracts.py; do not edit.',
             '// Shape-only types; runtime/conditional validation is defined by the source API section.',
             'export interface TlsConfig { enabled: boolean; ca_cert?: string | null; }']
    definitions = {}
    for name, num, label in specs:
        fs = fields(section(api, '#### ' + num + ' '), label)
        definitions[name] = {'source': 'API_CONTRACT_SPEC.md#' + num, 'fields': fs}
        types.append('// API §' + num + '\nexport interface ' + name + ' {\n' + '\n'.join('  ' + f['name'] + ('' if f['required'] else '?') + ': ' + f['type'] + ';' for f in fs) + '\n}')
    # Positive revision constraint and alias equality are runtime rules, not representable by number.
    types.append('export type DeleteUserRateLimitQuery = { revision: number; version?: number } | { version: number; revision?: number };')
    dto = re.search(r'export interface ProfileReadDTO \{[\s\S]*?\n\}', fe)[0]
    types.append(dto)
    fixture = json.loads(re.search(r'```json\n([\s\S]*?)```', section(api, '#### 6.5.1 '))[1])
    fixtures = {'profiles': fixture}
    for name, num, _ in specs:
        block = section(api, '#### ' + num + ' ')
        sample = re.search(r'- \*\*请求示例[^\n]*\n\s*```json\n([\s\S]*?)```', block)
        if sample:
            fixtures[name] = json.loads(sample[1])
    # Endpoint trace rows contain references, implementation ownership, and acceptance plans (not executed HTTP evidence).
    rows = []
    controllers = {'auth': 'Auth', 'approvals': 'Approval', 'users': 'User', 'pats': 'Pat', 'profiles': 'Profile', 'roles': 'Role', 'rate-limits': 'RateLimit', 'audits': 'Audit', 'settings': 'Settings'}
    be_matrix = section(be, '### 11.1 ')
    fe_matrix = section(fe, '### 8.1 ')
    for m in re.finditer(r'^#### (\S+) [^\n]+\n- \*\*接口路径\*\*：`([A-Z]+) (/api/v1/[^`]+)`', api, re.M):
        num, verb, route = m.groups()
        block = section(api, '#### ' + num + ' ')
        name = controllers[route.split('/')[3]]
        guard_match = re.search(r'- \*\*守卫级别\*\*：([^\n]+)', block)
        assert guard_match, (num, route, block[:350])
        guard = guard_match[1]
        access = next(l for l in db.splitlines() if l.startswith('| `' + verb + ' ' + route + '`'))
        fe_row = next(l for l in fe_matrix.splitlines() if re.search(r'`' + re.escape(route) + r'`\s*\|\s*`[^`]*\b' + verb + r'\b', l))
        be_row = next(l for l in be_matrix.splitlines() if re.search(r'`' + re.escape(route) + r'`\s*\|\s*`[^`]*\b' + verb + r'\b', l))
        memory_only = route in ['/api/v1/auth/csrf', '/api/v1/auth/logout', '/api/v1/profiles/test-db', '/api/v1/profiles/test-ssh', '/api/v1/settings/test-notify']
        rows.append({'method': verb, 'path': route, 'contractSection': num, 'schema': 'Contract_' + num.replace('.', '_'),
                     'controller': name + 'Controller', 'service': ('AuditExportService' if route.startswith('/api/v1/audits/export') else 'ProfileConnectivityService' if route in ('/api/v1/profiles/test-db', '/api/v1/profiles/test-ssh') else name + 'Service') + ' (§' + num + ')',
                     'repository': ('内存/外部探测；必要的审计落库见数据访问列' if memory_only else name + 'Repository'),
                     'dataAccess': access.split('|')[2].strip(), 'guard': guard,
                     'frontend': fe_row, 'backend': be_row,
                     'acceptance': '计划：契约有效输入/响应与字段白名单、守卫拒绝；' + ('读权限/过滤/脱敏' if verb == 'GET' else 'CSRF、业务校验、事务审计及适用的CAS/失效')})
    assert len(rows) == 47 and len({(r['method'], r['path']) for r in rows}) == 47
    lines = ['# 47项接口实现追踪（生成）', '', '> 这些是实施分工与验收计划，不代表已实现Controller/Schema/Service/Repository或已通过HTTP测试。Contract_* 是待落地的运行时Schema标识。', '', '| 方法与路径 | 契约/Schema | Controller / Service | Repository / 数据访问 | 守卫 | 前端/测试 |', '| --- | --- | --- | --- | --- | --- |']
    for r in rows:
        vals = ['`' + r['method'] + ' ' + r['path'] + '`', '§' + r['contractSection'] + ' / ' + r['schema'], r['controller'] + ' / ' + r['service'], r['repository'] + ' / ' + r['dataAccess'], r['guard'], '前端矩阵同方法路径；' + r['acceptance']]
        lines.append('| ' + ' | '.join(v.replace('|', '\\|') for v in vals) + ' |')
    return {'readiness.types.ts': '\n\n'.join(types) + '\n',
            'readiness.fixtures.json': json.dumps(fixtures, ensure_ascii=False, indent=2) + '\n',
            'request-fields.json': json.dumps(definitions, ensure_ascii=False, indent=2) + '\n',
            'endpoint-trace.json': json.dumps(rows, ensure_ascii=False, indent=2) + '\n',
            'ENDPOINT_TRACE.md': '\n'.join(lines) + '\n'}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    artifacts = generate()
    if args.check:
        for name, expected in artifacts.items():
            assert (OUT / name).read_text(encoding='utf-8') == expected, 'Generated artifact drift: ' + name
    else:
        OUT.mkdir(exist_ok=True)
        for name, content in artifacts.items():
            (OUT / name).write_text(content, encoding='utf-8', newline='\n')
    print('PASS: 47 endpoint traces; 8 generated request types; ProfileReadDTO; contract fixtures' + (' (no drift)' if args.check else ''))

if __name__ == '__main__':
    main()
